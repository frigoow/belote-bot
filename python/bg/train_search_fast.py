"""Train Search-Distilled BgFastPolicy (Expert Iteration) from bg_collect_search datasets.

Reads binary SearchSample records generated by `build/bg_collect_search`:
  - state[611] float32
  - legal_mask uint32 (canonical card bitmask)
  - trick uint8 (1..8)
  - contract_fam uint8 (0=suit, 1=nt, 2=at)
  - mult uint8 (1, 2, 4)
  - pad uint8
  - q_canon[32] float32 (normalized search Q-value = margin / mult; -1e9f if illegal)

Trains a compact BgFastPolicy (BGP1) with KL-divergence to softmax(q_canon / temp)
over legal moves, optional warm-start from an existing BGP1 binary, optional early-trick
weighting, and optional exact S_3 suit-permutation augmentation (for Suit).
"""

from __future__ import annotations

import argparse
import math
import struct
import time
from pathlib import Path

import numpy as np
import torch
import torch.nn.functional as F

import bg_cpp as bgc
from bg.models import BgFastPolicy
from bg.suit_perm import SuitPermuter

SAMPLE_DTYPE = np.dtype(
    [
        ("state", np.float32, (bgc.STATE_DIM,)),
        ("legal_mask", np.uint32),
        ("trick", np.uint8),
        ("contract_fam", np.uint8),
        ("mult", np.uint8),
        ("pad", np.uint8),
        ("q_canon", np.float32, (32,)),
    ],
    align=False,
)


def load_bgp1_into(model: BgFastPolicy, path: Path) -> None:
    """Load an existing BGP1 binary directly into a matching BgFastPolicy."""
    with path.open("rb") as f:
        magic = f.read(4)
        if magic != b"BGP1":
            raise ValueError(f"{path}: bad magic {magic!r}")
        ver, sdim, h1, h2, odim = struct.unpack("<5i", f.read(20))
        if (ver, sdim, h1, h2, odim) != (bgc.ENCODER_VERSION, model.state_dim, model.h1, model.h2, 32):
            raise ValueError(
                f"{path}: shape mismatch {(ver, sdim, h1, h2, odim)} vs "
                f"{(bgc.ENCODER_VERSION, model.state_dim, model.h1, model.h2, 32)}"
            )
        with torch.no_grad():
            for layer in (model.fc1, model.fc2, model.fc3):
                w = np.frombuffer(f.read(layer.weight.numel() * 4), dtype=np.float32).reshape(layer.weight.shape)
                b = np.frombuffer(f.read(layer.bias.numel() * 4), dtype=np.float32).reshape(layer.bias.shape)
                layer.weight.copy_(torch.from_numpy(w.copy()))
                layer.bias.copy_(torch.from_numpy(b.copy()))


def make_targets(q_canon: torch.Tensor, legal_mask: torch.Tensor, temp: float) -> torch.Tensor:
    q = q_canon.masked_fill(~legal_mask, -1e9)
    return F.softmax(q / temp, dim=-1)


@torch.no_grad()
def evaluate(
    model: BgFastPolicy,
    X: np.ndarray,
    M: np.ndarray,
    Q: np.ndarray,
    T: np.ndarray,
    temp: float,
    device: torch.device,
    bs: int = 4096,
) -> dict[str, float]:
    model.eval()
    n = len(X)
    tot_ce = 0.0
    tot_top1 = 0.0
    tot_regret = 0.0
    early_n = 0
    early_top1 = 0.0
    early_regret = 0.0
    for s in range(0, n, bs):
        xb = torch.from_numpy(X[s : s + bs]).to(device)
        mb = torch.from_numpy(M[s : s + bs]).to(device)
        qb = torch.from_numpy(Q[s : s + bs]).to(device)
        tb = torch.from_numpy(T[s : s + bs]).to(device)
        yb = make_targets(qb, mb, temp)

        logits = model(xb).masked_fill(~mb, -1e9)
        logp = F.log_softmax(logits, dim=-1)
        ce = -(yb * logp).sum(dim=-1)
        pred = logits.argmax(dim=-1)
        best_q = qb.masked_fill(~mb, -1e9).max(dim=-1).values
        pred_q = qb.gather(1, pred.unsqueeze(1)).squeeze(1)
        regret = best_q - pred_q
        top1 = (pred == qb.masked_fill(~mb, -1e9).argmax(dim=-1)).float()

        tot_ce += float(ce.sum().item())
        tot_top1 += float(top1.sum().item())
        tot_regret += float(regret.sum().item())

        early = tb <= 5
        ec = int(early.sum().item())
        if ec > 0:
            early_n += ec
            early_top1 += float(top1[early].sum().item())
            early_regret += float(regret[early].sum().item())

    return {
        "kl_ce": tot_ce / max(1, n),
        "top1": 100.0 * tot_top1 / max(1, n),
        "regret": tot_regret / max(1, n),
        "top1_t1_5": 100.0 * early_top1 / max(1, early_n),
        "regret_t1_5": early_regret / max(1, early_n),
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", type=Path, required=True, help="Binary dataset from bg_collect_search")
    ap.add_argument("--mode", choices=["suit", "nt", "at"], required=True)
    ap.add_argument("--out-bin", type=Path, required=True)
    ap.add_argument("--init-bin", type=Path, default=None, help="Optional BGP1 warm-start binary")
    ap.add_argument("--h1", type=int, default=256)
    ap.add_argument("--h2", type=int, default=128)
    ap.add_argument("--temp", type=float, default=1.5, help="Softmax temperature in normalized game points")
    ap.add_argument("--epochs", type=int, default=16)
    ap.add_argument("--batch-size", type=int, default=2048)
    ap.add_argument("--lr", type=float, default=1.5e-3)
    ap.add_argument("--min-lr", type=float, default=2e-5)
    ap.add_argument("--weight-decay", type=float, default=1e-4)
    ap.add_argument("--early-weight", type=float, default=1.0, help="Extra loss weight on Tricks 1-5")
    ap.add_argument("--suit-perm", action="store_true", help="Apply exact suit permutation (use S_3 for suit only!)")
    ap.add_argument("--val-frac", type=float, default=0.05)
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args()

    t0 = time.perf_counter()
    raw = np.fromfile(args.data, dtype=SAMPLE_DTYPE)
    n_total = len(raw)
    if n_total == 0:
        raise RuntimeError(f"Empty dataset: {args.data}")

    # Contiguous tail split keeps validation deals disjoint from training deals.
    n_val = max(1024, int(round(n_total * args.val_frac)))
    n_trn = n_total - n_val
    print(
        f"Loaded {n_total:,} search samples from {args.data} in {time.perf_counter() - t0:.2f}s "
        f"(train={n_trn:,}, val={n_val:,}, mode={args.mode}, T={args.temp}, h={args.h1}x{args.h2}, "
        f"init={'yes' if args.init_bin else 'no'}, suit_perm={args.suit_perm}, early_w={args.early_weight})",
        flush=True,
    )

    bits = np.arange(32, dtype=np.uint32)
    X_all = np.ascontiguousarray(raw["state"])
    M_all = ((raw["legal_mask"][:, None] >> bits[None, :]) & 1).astype(np.bool_)
    Q_all = np.ascontiguousarray(raw["q_canon"])
    T_all = np.ascontiguousarray(raw["trick"])

    X_trn, M_trn, Q_trn, T_trn = X_all[:n_trn], M_all[:n_trn], Q_all[:n_trn], T_all[:n_trn]
    X_val, M_val, Q_val, T_val = X_all[n_trn:], M_all[n_trn:], Q_all[n_trn:], T_all[n_trn:]

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    torch.manual_seed(args.seed)
    rng = np.random.default_rng(args.seed)

    model = BgFastPolicy(bgc.STATE_DIM, args.h1, args.h2).to(device)
    if args.init_bin is not None:
        load_bgp1_into(model, args.init_bin)
        v0 = evaluate(model, X_val, M_val, Q_val, T_val, args.temp, device)
        print(
            f"  [init {args.init_bin.name}] val kl_ce={v0['kl_ce']:.4f} top1={v0['top1']:.2f}% "
            f"regret={v0['regret']:.3f} | T1-5 top1={v0['top1_t1_5']:.2f}% regret={v0['regret_t1_5']:.3f}",
            flush=True,
        )

    opt = torch.optim.AdamW(model.parameters(), lr=args.lr, weight_decay=args.weight_decay)
    steps_per_ep = math.ceil(n_trn / args.batch_size)
    sched = torch.optim.lr_scheduler.CosineAnnealingLR(
        opt, T_max=args.epochs * steps_per_ep, eta_min=args.min_lr
    )
    permuter = SuitPermuter(args.mode, device) if args.suit_perm else None

    for ep in range(1, args.epochs + 1):
        model.train()
        order = rng.permutation(n_trn)
        tr_ce = 0.0
        tr_top1 = 0.0
        steps = 0
        for s in range(0, n_trn, args.batch_size):
            idx = order[s : s + args.batch_size]
            xb = torch.from_numpy(X_trn[idx]).to(device)
            mb = torch.from_numpy(M_trn[idx]).to(device)
            qb = torch.from_numpy(Q_trn[idx]).to(device)
            tb = torch.from_numpy(T_trn[idx]).to(device)
            if permuter is not None:
                pid = permuter.sample_perm_ids(xb.shape[0], device)
                xb = permuter.permute_state(xb, pid)
                mb = permuter.permute_cards_1d(mb, pid)
                qb = permuter.permute_cards_1d(qb, pid)
            yb = make_targets(qb, mb, args.temp)

            logits = model(xb).masked_fill(~mb, -1e9)
            logp = F.log_softmax(logits, dim=-1)
            per_ex = -(yb * logp).sum(dim=-1)
            if args.early_weight != 1.0:
                w = torch.where(tb <= 5, args.early_weight, 1.0)
                loss = (per_ex * w).sum() / w.sum()
            else:
                loss = per_ex.mean()

            opt.zero_grad(set_to_none=True)
            loss.backward()
            opt.step()
            sched.step()

            tr_ce += float(per_ex.mean().item())
            tr_top1 += float((logits.argmax(dim=-1) == qb.masked_fill(~mb, -1e9).argmax(dim=-1)).float().mean().item())
            steps += 1

        ev = evaluate(model, X_val, M_val, Q_val, T_val, args.temp, device)
        print(
            f"  ep {ep:2d}/{args.epochs} | trn ce={tr_ce/steps:.4f} top1={100*tr_top1/steps:.2f}% | "
            f"val ce={ev['kl_ce']:.4f} top1={ev['top1']:.2f}% regret={ev['regret']:.3f} | "
            f"T1-5 top1={ev['top1_t1_5']:.2f}% regret={ev['regret_t1_5']:.3f}",
            flush=True,
        )

    model.export_bin(args.out_bin)
    print(f"Exported search-distilled BgFastPolicy to {args.out_bin} ({time.perf_counter() - t0:.1f}s)", flush=True)


if __name__ == "__main__":
    main()
